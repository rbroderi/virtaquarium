// Copy the baked Roku assets (../assets, from `npm run bake`) into the package and generate the typed
// manifest module the app imports. Run before `rk dev` / `rk build`: `pnpm sync-assets`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.resolve(APP, '..', 'assets');
const DEST = path.join(APP, 'pkg', 'aquarium');
const MODULE = path.join(APP, 'src', 'aquarium', 'manifest.generated.ts');

const manifestPath = path.join(SRC, 'manifest.json');
if (!fs.existsSync(manifestPath)) {
  console.error(`No baked assets at ${SRC}. Run \`npm run bake\` in the project root first.`);
  process.exit(1);
}
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

fs.rmSync(DEST, { recursive: true, force: true });
let bytes = 0, files = 0;
for (const dir of ['fish', 'scenery']) {
  fs.mkdirSync(path.join(DEST, dir), { recursive: true });
  for (const name of fs.readdirSync(path.join(SRC, dir))) {
    fs.copyFileSync(path.join(SRC, dir, name), path.join(DEST, dir, name));
    bytes += fs.statSync(path.join(DEST, dir, name)).size;
    files++;
  }
}

fs.mkdirSync(path.dirname(MODULE), { recursive: true });
fs.writeFileSync(MODULE,
  '// Generated by scripts/sync-assets.mjs from roku/assets/manifest.json. Do not edit.\n' +
  '// eslint-disable-next-line @typescript-eslint/no-explicit-any\n' +
  `export const manifest: any = ${JSON.stringify(manifest)};\n` +
  `export const ASSET_ROOT = "pkg:/aquarium/";\n`);
console.log(`Copied ${files} files (${(bytes / 1e6).toFixed(1)} MB) to pkg/aquarium; wrote ${path.relative(APP, MODULE)}`);
